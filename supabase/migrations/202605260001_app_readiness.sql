create or replace function public.calculate_user_trust_score(p_user_id uuid)
returns integer
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_avg_stars numeric := 3;
  v_review_count integer := 0;
  v_attended_count integer := 0;
  v_hosted_count integer := 0;
  v_report_count integer := 0;
  v_review_component numeric := 0;
  v_score numeric := 50;
begin
  if p_user_id is null then
    return 0;
  end if;

  select coalesce(avg(stars), 3), count(*)
    into v_avg_stars, v_review_count
  from public.reviews
  where target_user_id = p_user_id;

  select count(*)
    into v_attended_count
  from public.bookings b
  join public.events e on e.event_id = b.event_id
  where b.user_id = p_user_id
    and b.booking_status = 'confirmed'
    and e.end_datetime < now();

  select count(*)
    into v_hosted_count
  from public.events e
  where e.organizer_user_id = p_user_id
    and e.end_datetime < now()
    and coalesce(e.status, 'published') <> 'cancelled';

  select count(*)
    into v_report_count
  from public.message_reports mr
  join public.chat_messages cm on cm.message_id = mr.message_id
  where cm.sender_user_id = p_user_id
    and mr.status in ('pending', 'confirmed', 'resolved');

  v_review_component := ((v_avg_stars - 3) * 10) + least(10, v_review_count * 2);
  v_score := 50
    + least(25, greatest(-25, v_review_component))
    + least(15, v_attended_count * 2)
    + least(15, v_hosted_count * 3)
    - least(20, v_report_count * 4);

  return greatest(0, least(100, round(v_score)))::integer;
end;
$$;

create or replace function public.refresh_user_trust_score(p_user_id uuid)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_score integer := 0;
  v_avg numeric := 0;
  v_count integer := 0;
begin
  if p_user_id is null then
    return 0;
  end if;

  v_score := public.calculate_user_trust_score(p_user_id);

  update public.personal_profiles
    set trust_score = v_score
  where user_id = p_user_id;

  select coalesce(avg(stars), 0), count(*)
    into v_avg, v_count
  from public.reviews
  where target_user_id = p_user_id;

  update public.business_profiles
    set trust_score = v_score,
        rating_avg = round(v_avg, 2),
        rating_count = v_count
  where user_id = p_user_id;

  return v_score;
end;
$$;

create or replace function public.refresh_event_rating(p_event_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_avg numeric := 0;
  v_count integer := 0;
begin
  if p_event_id is null then
    return;
  end if;

  select coalesce(avg(stars), 0), count(*)
    into v_avg, v_count
  from public.reviews
  where event_id = p_event_id;

  update public.events
    set rating_avg = round(v_avg, 2),
        rating_count = v_count
  where event_id = p_event_id;
end;
$$;

create or replace function public.handle_review_rollups()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op in ('INSERT', 'UPDATE') then
    perform public.refresh_user_trust_score(new.target_user_id);
    perform public.refresh_event_rating(new.event_id);
  end if;

  if tg_op in ('UPDATE', 'DELETE') then
    perform public.refresh_user_trust_score(old.target_user_id);
    perform public.refresh_event_rating(old.event_id);
  end if;

  return coalesce(new, old);
end;
$$;

