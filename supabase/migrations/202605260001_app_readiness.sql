create or replace function public.delete_current_user()
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_user_id uuid := auth.uid();
  v_personal_profile_ids bigint[];
  v_business_profile_ids bigint[];
  v_event_ids bigint[];
  v_chat_ids bigint[];
  v_booking_ids bigint[];
begin
  if v_user_id is null then
    raise exception 'Not authenticated';
  end if;

  select array_agg(profile_id::bigint)
    into v_personal_profile_ids
  from public.personal_profiles
  where user_id = v_user_id;

  select array_agg(business_profile_id::bigint)
    into v_business_profile_ids
  from public.business_profiles
  where user_id = v_user_id;

  select array_agg(event_id::bigint)
    into v_event_ids
  from public.events
  where organizer_user_id = v_user_id;

  select array_agg(chat_id::bigint)
    into v_chat_ids
  from public.event_chats
  where event_id = any(v_event_ids);

  select array_agg(booking_id::bigint)
    into v_booking_ids
  from public.bookings
  where user_id = v_user_id
     or event_id = any(v_event_ids);

  delete from public.payments
  where booking_id = any(v_booking_ids);

  delete from public.reviews
  where reviewer_user_id = v_user_id
     or target_user_id = v_user_id
     or target_personal_profile_id = any(v_personal_profile_ids)
     or target_business_profile_id = any(v_business_profile_ids)
     or event_id = any(v_event_ids);

  delete from public.message_reports
  where reporter_user_id = v_user_id
     or message_id in (
       select message_id
       from public.chat_messages
       where sender_user_id = v_user_id
          or chat_id = any(v_chat_ids)
     );

  delete from public.chat_messages
  where sender_user_id = v_user_id
     or chat_id = any(v_chat_ids);

  delete from public.event_chats
  where event_id = any(v_event_ids);

  delete from public.event_tags
  where event_id = any(v_event_ids);

  delete from public.bookings
  where user_id = v_user_id
     or event_id = any(v_event_ids);

  delete from public.events
  where organizer_user_id = v_user_id;

  delete from public.personal_profiles
  where user_id = v_user_id;

  delete from public.business_profiles
  where user_id = v_user_id;

  delete from public.users
  where user_id = v_user_id;

  delete from auth.users
  where id = v_user_id;
end;
$$;

grant execute on function public.calculate_user_trust_score(uuid) to authenticated;
